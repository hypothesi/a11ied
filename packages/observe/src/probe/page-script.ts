/** Lists targets under 24px and whether another target sits inside their 24px circle. */
export const SMALL_TARGETS_SCRIPT = [
   '(() => {',
   "      const els = [...document.querySelectorAll('a[href],button,input:not([type=hidden]),select,textarea,[role=button]')].filter((e) => { const b = e.getBoundingClientRect(); return b.width > 0 && b.height > 0; });",
   '      const boxes = els.map((e) => ({ e, b: e.getBoundingClientRect() }));',
   "      const inlineInText = (e) => getComputedStyle(e).display === 'inline' && e.closest('p,li,span,td');",
   '      const out = [];',
   '      for (const { e, b } of boxes) {',
   '         if (b.width >= 24 && b.height >= 24) { continue; }',
   '         if (inlineInText(e)) { continue; }',
   '         const cx = b.left + b.width / 2, cy = b.top + b.height / 2;',
   '         const crowded = boxes.some(({ e: o, b: ob }) => o !== e && !o.contains(e) && !e.contains(o) && Math.max(ob.left - cx, 0, cx - ob.right) ** 2 + Math.max(ob.top - cy, 0, cy - ob.bottom) ** 2 < 144);',
   '         out.push({ html: e.outerHTML.slice(0, 100), width: Math.round(b.width), height: Math.round(b.height), crowded });',
   '      }',
   '      return out;',
   '',
   '})()',
].join('\n');

/** Describes the element that currently holds keyboard focus. */
export const TAB_STOP_SCRIPT = [
   '(() => {',
   '         let e = document.activeElement;',
   '         while (e && e.shadowRoot && e.shadowRoot.activeElement) { e = e.shadowRoot.activeElement; }',
   '         if (!e || e === document.body) { return null; }',
   '         const cs = getComputedStyle(e), b = e.getBoundingClientRect();',
   '         const cx = Math.min(Math.max(b.left + b.width / 2, 0), innerWidth - 1), cy = Math.min(Math.max(b.top + b.height / 2, 0), innerHeight - 1);',
   '         let top = document.elementFromPoint(cx, cy);',
   '         for (let inner = top && top.shadowRoot && top.shadowRoot.elementFromPoint(cx, cy); inner && inner !== top; inner = top.shadowRoot && top.shadowRoot.elementFromPoint(cx, cy)) { top = inner; }',
   "         const parentIndicator = (() => { for (let n = e.parentElement; n && n !== document.body; n = n.parentElement) { const c = getComputedStyle(n); if ((c.outlineStyle !== 'none' && parseFloat(c.outlineWidth) > 0) || c.boxShadow !== 'none') { return true; } } return false; })();",
   "         return { tag: e.tagName, label: (e.getAttribute('aria-label') || e.textContent || '').trim().slice(0, 40), outline: (cs.outlineStyle !== 'none' && parseFloat(cs.outlineWidth) > 0) || parentIndicator, shadow: cs.boxShadow !== 'none' || parentIndicator, bg: cs.backgroundColor, color: cs.color, deco: cs.textDecorationLine, border: cs.borderTopColor + cs.borderTopWidth, top: Math.round(b.top + scrollY), left: Math.round(b.left), inView: b.bottom > 0 && b.top < innerHeight, obscured: !!top && top !== e && !e.contains(top) && !top.contains(e), hiddenFocus: (() => { for (let n = e; n && n !== document.body; n = n.parentElement) { const c = getComputedStyle(n); if (n.clientHeight === 0 && c.overflow === 'hidden' && n.scrollHeight > 0) { return true; } } return false; })(), id: e.tagName + ':' + (e.id || (e.textContent || '').trim().slice(0, 20)) };",
   '',
   '})()',
].join('\n');

/**
 * Tests whether focusing the target element changes its own styling or parent
 * focus-within styling.
 */
export const FOCUS_CHANGES_STYLE_SCRIPT = [
   '(probe) => {',
   '   let element = null;',
   '   if (probe.selector) {',
   '      element = document.querySelector(probe.selector);',
   "   } else if (typeof probe.index === 'number') {",
   "      element = document.querySelectorAll('*')[probe.index] || null;",
   '   }',
   '   if (!element) {',
   "      const colonIndex = probe.id.indexOf(':');",
   '      const tag = colonIndex >= 0 ? probe.id.slice(0, colonIndex) : probe.id;',
   "      const key = colonIndex >= 0 ? probe.id.slice(colonIndex + 1) : '';",
   '      const keyLength = probe.keyLength || 20;',
   "      element = [...document.querySelectorAll(tag || '*')].find(",
   "         (node) => (node.id || (node.textContent || '').trim().slice(0, keyLength)) === key,",
   '      ) || null;',
   '   }',
   '   if (!(element instanceof HTMLElement)) {',
   '      return undefined;',
   '   }',
   '   const describe = () => {',
   '      const computed = getComputedStyle(element);',
   '      const selfStyles = [',
   '         computed.outlineColor,',
   '         computed.outlineWidth,',
   '         computed.outlineStyle,',
   '         computed.boxShadow,',
   '         computed.borderTopColor,',
   '         computed.borderRightColor,',
   '         computed.borderBottomColor,',
   '         computed.borderLeftColor,',
   '         computed.backgroundColor,',
   '         computed.color,',
   '         computed.textDecorationLine,',
   '         computed.opacity,',
   '         computed.transform,',
   "      ].join('|');",
   '      const parentStyles = [];',
   '      for (let parent = element.parentElement; parent && parent !== document.documentElement; parent = parent.parentElement) {',
   '         const pc = getComputedStyle(parent);',
   '         parentStyles.push([',
   '            pc.outlineColor,',
   '            pc.outlineWidth,',
   '            pc.outlineStyle,',
   '            pc.boxShadow,',
   '            pc.borderTopColor,',
   '            pc.borderRightColor,',
   '            pc.borderBottomColor,',
   '            pc.borderLeftColor,',
   "         ].join(';'));",
   '      }',
   '      return selfStyles + "#" + parentStyles.join(";");',
   '   };',
   '   element.blur();',
   '   const before = describe();',
   '   element.focus({ focusVisible: true });',
   '   return before !== describe();',
   '}',
].join('\n');

/** Counts media playback, audio contexts, and motion listeners before page scripts run. */
export const INSTRUMENT_SCRIPT = [
   '(() => {',
   'window.__a11 = { mediaPlays: 0, audioContexts: 0, motionListeners: [] };',
   'const play = HTMLMediaElement.prototype.play;',
   'HTMLMediaElement.prototype.play = function (...args) { window.__a11.mediaPlays += 1; return play.apply(this, args); };',
   "for (const name of ['AudioContext', 'webkitAudioContext']) {",
   '   const Orig = window[name];',
   '   if (Orig) { window[name] = function (...args) { window.__a11.audioContexts += 1; return new Orig(...args); }; }',
   '}',
   'const add = EventTarget.prototype.addEventListener;',
   'EventTarget.prototype.addEventListener = function (type, ...rest) { if (/^device(motion|orientation)$/.test(type)) { window.__a11.motionListeners.push(type); } return add.call(this, type, ...rest); };',
   '})()',
].join('\n');
